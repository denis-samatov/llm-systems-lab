"""Generate ``results/REPORT.md`` and figures from benchmark JSON files.

Only files that exist are reported; a missing suite is listed as "not run" rather than
silently omitted, so the report never implies coverage it does not have.
"""

from __future__ import annotations

import json
from pathlib import Path

SUITES = [
    "train_parallel",
    "comm",
    "engine_offline",
    "engine_online",
    "engine_prefix",
    "spec",
    "quant",
    "kvcalc",
    "lora",
    "profile",
    "gpu_serving",
]


def _load(results: Path, name: str) -> dict | None:
    p = results / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def _fmt(v, digits=3):
    if v is None:
        return "-"
    if isinstance(v, float):
        if abs(v) >= 1000:
            return f"{v:,.0f}"
        return f"{v:.{digits}f}"
    return str(v)


def _table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(_fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _mb(b):
    return None if b is None else b / 2**20


def _plt():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({"figure.dpi": 110, "axes.grid": True, "grid.alpha": 0.3, "font.size": 9})
    return plt


def build_report(results: Path, runs: Path) -> Path:
    fig_dir = results / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    plt = _plt()
    md = [
        "# llm-systems-lab: benchmark report",
        "",
        "Generated by `llmlab report` from the JSON files in `results/`. Hardware and package versions",
        "are recorded in each file's `manifest`. **All measurements below were taken on CPU**; multi-process",
        "rows validate distributed semantics and overhead on one host, not multi-GPU scaling.",
        "",
    ]
    missing = [s for s in SUITES if _load(results, s) is None]

    tp = _load(results, "train_parallel")
    if tp:
        hw = tp["manifest"]["hardware"]
        md += [
            "## 1. Training: single device vs DDP vs FSDP2",
            "",
            f"Host: {hw.get('cpu_model', '?')}, {hw['cpu_count']} logical CPUs. Global batch fixed at "
            f"{tp['rows'][0]['global_batch_tokens']} tokens; {tp['steps']} steps; CPU threads split evenly "
            "across ranks.",
            "",
        ]
        rows = []
        for r in tp["rows"]:
            m = r["memory_rank0"]
            rows.append(
                [
                    r["row"],
                    r["nproc"],
                    r["precision"],
                    r["tokens_per_s"],
                    r["mean_step_s"],
                    r["final_loss"],
                    _mb(m["param_bytes"]),
                    _mb(m["grad_bytes"]),
                    _mb(m["optim_bytes"]),
                    _mb(r["peak_rss_bytes_rank0"]),
                ]
            )
        md.append(
            _table(
                [
                    "run",
                    "ranks",
                    "precision",
                    "tokens/s",
                    "step s",
                    "final loss",
                    "params MiB/rank",
                    "grads MiB/rank",
                    "Adam MiB/rank",
                    "peak RSS MiB (rank 0)",
                ],
                rows,
            )
        )
        fig, ax = plt.subplots(1, 2, figsize=(10, 3.4))
        for r in tp["rows"]:
            s, loss = zip(*r["curve"], strict=True)
            ax[0].plot(s, loss, label=r["row"], lw=1)
        ax[0].set(xlabel="step", ylabel="train loss", title="Loss curves (same global batch)")
        ax[0].legend(fontsize=7)
        names = [r["row"] for r in tp["rows"]]
        state = [_mb(r["memory_rank0"]["total_bytes"]) for r in tp["rows"]]
        ax[1].barh(names, state, color="#4c78a8")
        ax[1].set(xlabel="MiB per rank", title="Params + grads + Adam state per rank")
        fig.tight_layout()
        fig.savefig(fig_dir / "train_parallel.png")
        plt.close(fig)
        md += ["", "![training](figures/train_parallel.png)", ""]

    comm = _load(results, "comm")
    if comm:
        md += ["## 2. All-reduce bandwidth (gloo, loopback TCP on one host)", ""]
        fig, ax = plt.subplots(figsize=(5, 3.2))
        rows = []
        for w in comm["worlds"]:
            xs = [r["bytes"] for r in w["rows"]]
            ax.plot(xs, [r["busbw_GBps"] for r in w["rows"]], marker="o", label=f"world={w['world_size']}")
            for r in w["rows"]:
                rows.append(
                    [
                        w["world_size"],
                        r["bytes"] / 1024,
                        r["seconds_p50"] * 1e3,
                        r["algbw_GBps"],
                        r["busbw_GBps"],
                    ]
                )
        ax.set(xscale="log", xlabel="message bytes", ylabel="bus bandwidth GB/s", title="gloo all_reduce")
        ax.legend()
        fig.tight_layout()
        fig.savefig(fig_dir / "comm.png")
        plt.close(fig)
        md += [
            _table(["world", "KiB", "p50 ms", "algbw GB/s", "busbw GB/s"], rows),
            "",
            "![comm](figures/comm.png)",
            "",
        ]

    off = _load(results, "engine_offline")
    if off:
        md += [
            "## 3. Serving: static vs continuous batching (offline, all requests at t=0)",
            "",
            f"{off['requests']} requests, prompts are prefixes of dev complaints, max_new_tokens ~ U(16,128); "
            f"KV cache {off['kv_bytes_per_token']} B/token (fp32, GQA 4 KV heads).",
            "",
        ]
        rows = []
        for r in off["rows"]:
            kv = r.get("kv_reserved_peak_bytes") or r.get("kv_used_peak_bytes")
            rows.append(
                [
                    r["system"],
                    r.get("requests", off["requests"]),
                    r["output_tok_per_s"],
                    r["wall_s"],
                    (r.get("ttft_s") or {}).get("p50"),
                    (r.get("ttft_s") or {}).get("p95"),
                    (r.get("tpot_s") or {}).get("p50"),
                    _mb(kv),
                ]
            )
        md.append(
            _table(
                [
                    "system",
                    "requests",
                    "output tok/s",
                    "wall s",
                    "TTFT p50 s",
                    "TTFT p95 s",
                    "TPOT p50 s",
                    "KV peak MiB",
                ],
                rows,
            )
        )
        sys_rows = [r for r in off["rows"] if r["system"].startswith(("static", "continuous"))]
        fig, ax = plt.subplots(figsize=(5.5, 3.2))
        ax.bar(
            [r["system"] for r in sys_rows],
            [r["output_tok_per_s"] for r in sys_rows],
            color=["#e45756" if r["system"].startswith("static") else "#4c78a8" for r in sys_rows],
        )
        ax.set(ylabel="output tokens/s", title="Offline throughput")
        ax.tick_params(axis="x", rotation=20)
        fig.tight_layout()
        fig.savefig(fig_dir / "engine_offline.png")
        plt.close(fig)
        md += [
            "",
            "Static batches reserve KV for `batch x (longest prompt + max_new)`; the paged pool holds only",
            "the blocks in use. `KV peak` is reserved bytes for static rows and peak used blocks for continuous rows.",
            "",
            "![offline](figures/engine_offline.png)",
            "",
        ]

    on = _load(results, "engine_online")
    if on:
        md += ["## 4. Serving under load (Poisson arrivals, continuous batching, max 16 seqs)", ""]
        rows = [
            [
                r["rate_rps"],
                r["output_tok_per_s"],
                r["ttft_s"]["p50"],
                r["ttft_s"]["p95"],
                r["tpot_s"]["p50"],
                r["tpot_s"]["p95"],
                r["e2e_s"]["p95"],
                r["mean_batch_seqs"],
            ]
            for r in on["rows"]
        ]
        md.append(
            _table(
                [
                    "rate req/s",
                    "output tok/s",
                    "TTFT p50",
                    "TTFT p95",
                    "TPOT p50",
                    "TPOT p95",
                    "E2E p95",
                    "mean seqs/step",
                ],
                rows,
            )
        )
        fig, ax = plt.subplots(figsize=(5, 3.2))
        ax.plot(
            [r["rate_rps"] for r in on["rows"]],
            [r["ttft_s"]["p95"] for r in on["rows"]],
            marker="o",
            label="TTFT p95",
        )
        ax.plot(
            [r["rate_rps"] for r in on["rows"]],
            [r["tpot_s"]["p95"] for r in on["rows"]],
            marker="o",
            label="TPOT p95",
        )
        ax.set(xlabel="arrival rate (req/s)", ylabel="seconds", yscale="log", title="Latency vs load")
        ax.legend()
        fig.tight_layout()
        fig.savefig(fig_dir / "engine_online.png")
        plt.close(fig)
        md += ["", "![online](figures/engine_online.png)", ""]

    pre = _load(results, "engine_prefix")
    if pre:
        md += ["## 5. Prefix caching (shared 64-token system prompt)", ""]
        rows = [
            [
                r["system"],
                r["prefill_tokens_computed"],
                r["prompt_tokens_from_cache"],
                r["ttft_s"]["p50"],
                r["ttft_s"]["p95"],
                r["output_tok_per_s"],
                r["allocator"]["prefix_hits"],
            ]
            for r in pre["rows"]
        ]
        md += [
            _table(
                [
                    "system",
                    "prefill tokens computed",
                    "prompt tokens from cache",
                    "TTFT p50",
                    "TTFT p95",
                    "output tok/s",
                    "block hits",
                ],
                rows,
            ),
            "",
        ]

    sp = _load(results, "spec")
    if sp:
        md += [
            "## 6. Speculative decoding (draft model, batch 1)",
            "",
            f"Target {sp['target_params']:,} params, draft {sp['draft_params']:,} params; draft decode costs "
            f"{sp['draft_cost_ratio']:.2f}x of target decode time. {sp['prompts']} dev prompts x "
            f"{sp['max_new_tokens']} tokens.",
            "",
        ]
        rows = [
            [
                r["k"],
                r["temperature"],
                r["acceptance_rate"],
                r["tokens_per_target_forward"],
                r["speedup_vs_target_only"],
                r["greedy_outputs_identical"],
            ]
            for r in sp["rows"]
        ]
        md.append(
            _table(
                [
                    "k",
                    "temperature",
                    "acceptance",
                    "tokens / target forward",
                    "speedup",
                    "greedy outputs identical (of prompts)",
                ],
                rows,
            )
        )
        fig, ax = plt.subplots(figsize=(5, 3.2))
        for t in sorted({r["temperature"] for r in sp["rows"]}):
            rr = [r for r in sp["rows"] if r["temperature"] == t]
            ax.plot(
                [r["k"] for r in rr], [r["speedup_vs_target_only"] for r in rr], marker="o", label=f"T={t}"
            )
        ax.axhline(1.0, color="gray", lw=0.8)
        ax.set(
            xlabel="draft tokens per round (k)", ylabel="speedup vs target-only", title="Speculative decoding"
        )
        ax.legend()
        fig.tight_layout()
        fig.savefig(fig_dir / "spec.png")
        plt.close(fig)
        md += ["", "![spec](figures/spec.png)", ""]

    q = _load(results, "quant")
    if q:
        md += ["## 7. Weight quantization", "", q["note"], ""]
        rows = [
            [
                r["scheme"],
                r["dev_perplexity"],
                _mb(r["weight_bytes"]),
                r["decode_tok_per_s_b1"]["p50"],
                r["prefill_tok_per_s_b16"],
            ]
            for r in q["rows"]
        ]
        md += [
            _table(
                [
                    "scheme",
                    "dev perplexity",
                    "weights MiB",
                    "decode tok/s (b=1, p50)",
                    "prefill tok/s (b=16)",
                ],
                rows,
            ),
            "",
        ]

    kv = _load(results, "kvcalc")
    if kv:
        a = kv["assumptions"]
        md += [
            "## 8. KV-cache memory: analytic sizing (calculation, not a measurement)",
            "",
            f"Assumptions: {a['gpu_memory_gb']} GB GPU, {a['gpu_memory_utilization']:.0%} usable, bf16 weights, "
            f"{a['seq_len']}-token sequences, activations ignored.",
            "",
        ]
        rows = [
            [
                r["model"],
                r["kv_dtype"],
                r["kv_bytes_per_token"],
                r["kv_gib_per_seq"],
                r["max_concurrent_seqs"],
            ]
            for r in kv["rows"]
        ]
        md += [
            _table(["model", "KV dtype", "bytes/token", "GiB per sequence", "max concurrent seqs"], rows),
            "",
        ]

    lo = _load(results, "lora")
    if lo:
        md += [
            "## 9. Downstream fine-tuning: LoRA vs full fine-tune vs probe vs TF-IDF (RuMedTop3 test, n=822)",
            "",
        ]
        rows = []
        for r in lo["rows"]:
            ci = r["test_hit1_ci95"]
            rows.append(
                [
                    r["method"],
                    r["test_hit1"],
                    f"[{ci[0]:.3f}, {ci[1]:.3f}]",
                    r["test_hit3"],
                    r.get("dev_hit1_best"),
                    r.get("trainable_params"),
                    _mb(r.get("optimizer_state_bytes")),
                    r.get("mean_step_s"),
                ]
            )
        md += [
            _table(
                [
                    "method",
                    "test Hit@1",
                    "95% CI",
                    "test Hit@3",
                    "dev Hit@1 (selected)",
                    "trainable params",
                    "Adam state MiB",
                    "step s (during run)",
                ],
                rows,
            ),
            "",
            "Step times in this table were recorded during the quality run, which shared the CPU with other",
            "jobs; use the isolated timing table below for speed comparisons.",
            "",
        ]
        lt = _load(results, "lora_timing")
        if lt:
            md += [
                "**Isolated step timing** (`llmlab bench lora timing`, idle host, batch 32 x 128):",
                "",
                _table(
                    ["method", "median step s", "p90 step s"],
                    [[r["method"], r["median_step_s"], r["p90_step_s"]] for r in lt["rows"]],
                ),
                "",
            ]

    pr = _load(results, "profile")
    if pr:
        md += ["## 10. Profiles (torch.profiler, CPU)", ""]
        for key, title in (
            ("train_step", "Training step (batch 16 x 127)"),
            ("decode_step_16_seqs", "Engine decode step, 16 sequences"),
        ):
            md += [
                f"**{title}** - top operators by self CPU time:",
                "",
                _table(
                    ["op", "calls", "self ms", "% self"],
                    [[r["op"], r["calls"], r["self_cpu_ms"], r["self_cpu_pct"]] for r in pr[key][:8]],
                ),
                "",
            ]
        md += ["Chrome traces: `results/profile_*.json.gz` (open in Perfetto / chrome://tracing).", ""]

    gpu = _load(results, "gpu_serving")
    md += ["## 11. GPU serving (vLLM / SGLang)", ""]
    if gpu:
        md.append(
            _table(
                ["id", "rate", "output tok/s", "TTFT p50 ms", "TPOT p50 ms"],
                [
                    [r["id"], r["rate"], r["output_throughput"], r["median_ttft_ms"], r["median_tpot_ms"]]
                    for r in gpu["rows"]
                ],
            )
        )
    else:
        md += [
            "**Not run.** No GPU was available. The matrix and harness are in `gpu/` "
            "(`gpu/README.md`); `gpu/run_matrix.py` refuses to run without CUDA.",
            "",
        ]
    if missing:
        md += ["## Suites without results", "", ", ".join(f"`{m}`" for m in missing), ""]
    path = results / "REPORT.md"
    path.write_text("\n".join(md) + "\n", encoding="utf-8")
    return path
